/**
 * Cross-check between the web client and the program.
 *
 * Builds the same instructions the app sends (through src/lib/program.ts) for
 * a whole invoice life cycle and writes them to a JSON file. The Rust test
 * programs/sooner/tests/js_client.rs then executes them against the program
 * in-process. If the client and the program ever disagree about an account
 * order or an argument type, that test fails.
 *
 *   npm run fixture        (from app/)
 *   cargo test -p sooner   (from the repository root)
 */
import { Connection, Keypair, type PublicKey, type TransactionInstruction } from '@solana/web3.js';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import {
  approveIx,
  claimIxs,
  demoMintPda,
  faucetIxs,
  fundIx,
  getProgram,
  initializeIx,
  invoiceIdFor,
  openPoolIx,
  payablePda,
  poolPda,
  setRateIx,
  settleIxs,
  vaultPda,
  voidIx,
  withdrawIxs,
  type ConfigView,
  type PayableView,
  type PoolView,
} from '../src/lib/program';

const T0 = 1_800_000_000; // the Rust test starts its clock here
const DAY = 86_400;
const USD = 1_000_000n;

type Step = { label: string; signer: 'buyer' | 'supplier'; instructions: TransactionInstruction[] };

const hex = (bytes: Uint8Array) => Buffer.from(bytes).toString('hex');

async function main() {
  // No request is ever sent: building instructions needs no network.
  const program = getProgram(new Connection('http://127.0.0.1:1', 'confirmed'));
  const buyer = Keypair.generate();
  const supplier = Keypair.generate();
  const mint = demoMintPda();
  const poolAddress = poolPda(buyer.publicKey, mint);

  const config: ConfigView = { admin: buyer.publicKey, treasury: buyer.publicKey, feeBps: 1000, demoMint: mint };
  const pool = (vaultBalance: bigint): PoolView => ({
    address: poolAddress,
    buyer: buyer.publicKey,
    mint,
    vault: vaultPda(poolAddress),
    rateBps: 1200,
    createdAt: T0,
    outstanding: 0n,
    totalApproved: 0n,
    totalPaid: 0n,
    totalDiscount: 0n,
    totalFees: 0n,
    countApproved: 0,
    countEarly: 0,
    countOnTime: 0,
    countLate: 0,
    countVoided: 0,
    secondsEarly: 0n,
    secondsLate: 0n,
    vaultBalance,
  });
  const payable = async (reference: string, amount: bigint, to: PublicKey): Promise<PayableView> => {
    const invoiceId = await invoiceIdFor(reference);
    return {
      address: payablePda(poolAddress, invoiceId),
      pool: poolAddress,
      supplier: to,
      amount,
      rateBps: 1200,
      approvedAt: T0,
      dueAt: T0 + 45 * DAY,
      status: 'open',
      paidAt: 0,
      paidAmount: 0n,
      discount: 0n,
      invoiceId,
      reference,
    };
  };

  const first = await payable('INV-1042', 1_000n * USD, supplier.publicKey);
  const second = await payable('INV-1043', 2_650n * USD, supplier.publicKey);
  const third = await payable('INV-1044', 400n * USD, supplier.publicKey);
  const approve = (p: PayableView) =>
    approveIx(program, pool(0n), p.supplier, p.amount, p.dueAt, p.reference, p.invoiceId);

  const steps: Step[] = [
    { label: 'set up the deployment', signer: 'buyer', instructions: [await initializeIx(program, buyer.publicKey, 1000)] },
    { label: 'get test dollars', signer: 'buyer', instructions: await faucetIxs(program, buyer.publicKey, buyer.publicKey, mint) },
    { label: 'open the pool', signer: 'buyer', instructions: [await openPoolIx(program, buyer.publicKey, mint, 1200)] },
    { label: 'add cash', signer: 'buyer', instructions: [await fundIx(program, buyer.publicKey, pool(0n), 1_500n * USD)] },
    { label: 'approve INV-1042', signer: 'buyer', instructions: [await approve(first)] },
    { label: 'supplier takes INV-1042 early', signer: 'supplier', instructions: await claimIxs(program, config, pool(1_500n * USD), first) },
    { label: 'approve INV-1043', signer: 'buyer', instructions: [await approve(second)] },
    // The vault now holds less than 2,650, so the client adds a top-up before paying in full.
    { label: 'buyer pays INV-1043 in full', signer: 'buyer', instructions: await settleIxs(program, pool(500n * USD), second) },
    { label: 'change the rate', signer: 'buyer', instructions: [await setRateIx(program, pool(0n), 1800)] },
    { label: 'approve INV-1044', signer: 'buyer', instructions: [await approve(third)] },
    { label: 'supplier releases INV-1044', signer: 'supplier', instructions: [await voidIx(program, third)] },
    { label: 'add cash again', signer: 'buyer', instructions: [await fundIx(program, buyer.publicKey, pool(0n), 300n * USD)] },
    { label: 'take cash out', signer: 'buyer', instructions: await withdrawIxs(program, pool(300n * USD), 100n * USD) },
  ];

  const fixture = {
    note: 'Generated by app/scripts/client-fixture.ts. Test keys only; they never hold real funds.',
    programId: program.programId.toBase58(),
    clock: T0,
    keys: { buyer: Array.from(buyer.secretKey), supplier: Array.from(supplier.secretKey) },
    payables: {
      first: first.address.toBase58(),
      second: second.address.toBase58(),
      third: third.address.toBase58(),
    },
    steps: steps.map((step) => ({
      label: step.label,
      signer: step.signer,
      instructions: step.instructions.map((ix) => ({
        programId: ix.programId.toBase58(),
        accounts: ix.keys.map((k) => ({ pubkey: k.pubkey.toBase58(), isSigner: k.isSigner, isWritable: k.isWritable })),
        data: hex(ix.data),
      })),
    })),
  };

  const out = resolve(__dirname, '../../programs/sooner/tests/fixtures/js-client.json');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, JSON.stringify(fixture, null, 2) + '\n');
  console.log(`wrote ${steps.length} steps to ${out}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
